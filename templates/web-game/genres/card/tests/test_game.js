// 52장 덱·점수·허용된 턴 전이와 결과를 검사한다.
'use strict';
const assert=require('node:assert/strict');
const Game=require('../static/game.js');
const cards=(...ranks)=>ranks.map(rank=>({suit:'♠',rank}));
const deck=Game.createDeck();
assert.equal(deck.length,52);
assert.equal(new Set(deck.map(c=>`${c.suit}${c.rank}`)).size,52);
assert.deepEqual(Game.shuffle(deck,()=>0),Game.shuffle(deck,()=>0));
assert.notDeepEqual(Game.shuffle(deck,()=>0),deck);
assert.deepEqual(deck,Game.createDeck());
assert.equal(Game.total(cards(1,1,9)),21);
assert.equal(Game.total(cards(1,13)),21);
assert.equal(Game.total(cards(1,1,13,9)),21);
const state=Game.createGame(()=>0);
for(const action of [Game.hit,Game.stand,Game.playDealer]) assert.equal(action(state),false);
assert.equal(Game.deal(state),true);
assert.equal(state.phase,'player'); assert.equal(state.deck.length,48);
assert.equal(state.player.length,2); assert.equal(state.dealer.length,2);
assert.equal(Game.deal(state),false); assert.equal(Game.playDealer(state),false);
state.paused=true;
for(const action of [Game.hit,Game.stand,Game.deal]) assert.equal(action(state),false);
state.paused=false;
state.player=cards(10,9); state.deck=cards(5);
assert.equal(Game.hit(state),true); assert.equal(state.result,'lose'); assert.equal(state.score,0);
assert.equal(Game.hit(state),false); assert.equal(Game.stand(state),false);
Game.deal(state); state.player=cards(10,9); state.dealer=cards(10,6); state.deck=cards(10);
assert.equal(Game.stand(state),true); assert.equal(state.phase,'dealer');
assert.equal(Game.hit(state),false); assert.equal(Game.deal(state),false);
assert.equal(Game.playDealer(state),true); assert.equal(state.result,'win'); assert.equal(state.score,1);
assert.equal(Game.playDealer(state),false); assert.equal(state.score,1);
Game.deal(state); assert.equal(state.score,1);
state.player=cards(10,7); state.dealer=cards(1,6); state.deck=cards(10);
Game.stand(state); Game.playDealer(state);
assert.equal(state.result,'draw'); assert.equal(state.deck.length,1);
Game.deal(state); state.player=cards(10,7); state.dealer=cards(10,8);
Game.stand(state); Game.playDealer(state); assert.equal(state.result,'lose');
console.log('OK — 덱·에이스·턴 거절·버스트·딜러 17·승패·승리 수');
